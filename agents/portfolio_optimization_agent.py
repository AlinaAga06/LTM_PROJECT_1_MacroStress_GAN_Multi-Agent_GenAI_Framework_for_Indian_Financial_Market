"""
MacroStress-GAN
Portfolio Optimization Agent V2
Stock Market TimeGAN V2

Purpose
-------
Optimize institutional stock-market portfolio weights using the SAME
baseline and stressed TimeGAN paths generated by SimulationAgent.

Important
---------
1. No new synthetic data is generated.
2. No TimeGAN model is loaded here.
3. baseline_raw and stressed_raw are supplied by the orchestrator.
4. Original document weights are preserved exactly.
5. Asset weights are optimized under minimum/maximum constraints.
6. The optimization objective is expected stressed monetary loss.
7. The final reported objective is always recomputed from the FINAL
   optimized weights.
8. Asset "sensitivities" from the institution document are supported.
9. The output structure is compatible with the orchestrator's
   Phase 7, Phase 8, and Phase 9 validation logic.
"""

