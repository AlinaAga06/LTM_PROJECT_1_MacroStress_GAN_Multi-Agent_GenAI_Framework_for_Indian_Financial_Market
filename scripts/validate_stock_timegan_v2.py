# RANGE COVERAGE
# =============================================================================

def calculate_range_coverage(
    real_data,
    synthetic_data
):

    print()
    print("=" * 78)
    print("7. RANGE COVERAGE")
    print("=" * 78)

    rows = []

    for i, feature in enumerate(
        FEATURE_NAMES
    ):

        real_min = np.min(
            real_data[
                :,
                i
            ]
        )

        real_max = np.max(
            real_data[
                :,
                i
            ]
        )

        synthetic_min = np.min(
            synthetic_data[
                :,
                i
            ]
        )

        synthetic_max = np.max(
            synthetic_data[
                :,
                i
            ]
        )

        lower_gap = max(
            0.0,
            real_min - synthetic_min
        )

        upper_gap = max(
            0.0,
            synthetic_max - real_max
        )

        real_range = (
            real_max
            - real_min
        )

        covered_range = (
            min(
                real_max,
                synthetic_max
            )
            -
            max(
                real_min,
                synthetic_min
            )
        )

        if real_range > 0:

            range_coverage_ratio = (
                max(
                    0.0,
                    covered_range
                )
                / real_range
            )

        else:

            range_coverage_ratio = np.nan

        rows.append({

            "Feature":
                feature,

            "Real_Min":
                real_min,

            "Synthetic_Min":
                synthetic_min,

            "Real_Max":
                real_max,

            "Synthetic_Max":
                synthetic_max,

            "Lower_Gap":
                lower_gap,

            "Upper_Gap":
                upper_gap,

            "Range_Coverage_Ratio":
                range_coverage_ratio
        })

        print()
        print(feature)

        print(
            f"  Real range       : "
            f"{real_min:.8f} → {real_max:.8f}"
        )

        print(
            f"  Synthetic range  : "
            f"{synthetic_min:.8f} → {synthetic_max:.8f}"
        )

        print(
            f"  Range coverage   : "
            f"{range_coverage_ratio:.4f}"
        )

    return pd.DataFrame(
        rows
    )


