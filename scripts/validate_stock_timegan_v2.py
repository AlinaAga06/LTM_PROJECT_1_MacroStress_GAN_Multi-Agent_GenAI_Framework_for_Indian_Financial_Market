# =============================================================================
# EXTREME EVENT COVERAGE
# =============================================================================

def calculate_extreme_events(
    real_data,
    synthetic_data
):

    print()
    print("=" * 78)
    print("4. EXTREME-EVENT COVERAGE")
    print("=" * 78)

    rows = []

    for i, feature in enumerate(
        FEATURE_NAMES
    ):

        real_values = real_data[
            :,
            i
        ]

        synthetic_values = synthetic_data[
            :,
            i
        ]

        lower_threshold = np.quantile(
            real_values,
            LOW_QUANTILE
        )

        upper_threshold = np.quantile(
            real_values,
            HIGH_QUANTILE
        )

        real_lower = np.sum(
            real_values
            <= lower_threshold
        )

        synthetic_lower = np.sum(
            synthetic_values
            <= lower_threshold
        )

        real_upper = np.sum(
            real_values
            >= upper_threshold
        )

        synthetic_upper = np.sum(
            synthetic_values
            >= upper_threshold
        )

        rows.append({

            "Feature":
                feature,

            "Real_Lower_1pct_Threshold":
                lower_threshold,

            "Real_Upper_99pct_Threshold":
                upper_threshold,

            "Real_Lower_Count":
                real_lower,

            "Synthetic_Lower_Count":
                synthetic_lower,

            "Real_Upper_Count":
                real_upper,

            "Synthetic_Upper_Count":
                synthetic_upper,

            "Lower_Coverage_Ratio":
                (
                    synthetic_lower
                    / real_lower
                    if real_lower > 0
                    else np.nan
                ),

            "Upper_Coverage_Ratio":
                (
                    synthetic_upper
                    / real_upper
                    if real_upper > 0
                    else np.nan
                )
        })

        print()
        print(feature)

        print(
            f"  Lower 1% threshold : "
            f"{lower_threshold:.8f}"
        )

        print(
            f"  Real lower count   : "
            f"{real_lower}"
        )

        print(
            f"  Synth lower count  : "
            f"{synthetic_lower}"
        )

        print(
            f"  Upper 99% threshold: "
            f"{upper_threshold:.8f}"
        )

        print(
            f"  Real upper count   : "
            f"{real_upper}"
        )

        print(
            f"  Synth upper count  : "
            f"{synthetic_upper}"
        )

    return pd.DataFrame(
        rows
    )


# =============================================================================
# DISTRIBUTION TESTS
# =============================================================================

def calculate_distribution_tests(
    real_data,
    synthetic_data
):

    print()
    print("=" * 78)
    print("5. DISTRIBUTION SIMILARITY")
    print("=" * 78)

    rows = []

    ks_values = []
    wasserstein_values = []

    for i, feature in enumerate(
        FEATURE_NAMES
    ):

        real_values = real_data[
            :,
            i
        ]

        synthetic_values = synthetic_data[
            :,
            i
        ]

        ks_result = ks_2samp(
            real_values,
            synthetic_values
        )

        ks_statistic = (
            ks_result.statistic
        )

        wasserstein = (
            wasserstein_distance(
                real_values,
                synthetic_values
            )
        )

        ks_values.append(
            ks_statistic
        )

        wasserstein_values.append(
            wasserstein
        )

        rows.append({

            "Feature":
                feature,

            "KS_Statistic":
                ks_statistic,

            "KS_p_value":
                ks_result.pvalue,

            "Wasserstein_Distance":
                wasserstein
        })

        print()
        print(feature)

        print(
            f"  KS statistic       : "
            f"{ks_statistic:.6f}"
        )

        print(
            f"  KS p-value         : "
            f"{ks_result.pvalue:.6e}"
        )

        print(
            f"  Wasserstein        : "
            f"{wasserstein:.6f}"
        )

    mean_ks = np.mean(
        ks_values
    )

    mean_wasserstein = np.mean(
        wasserstein_values
    )

    print()
    print(
        f"Mean KS statistic       : "
        f"{mean_ks:.6f}"
    )

    print(
        f"Mean Wasserstein        : "
        f"{mean_wasserstein:.6f}"
    )

    return (
        pd.DataFrame(rows),
        mean_ks,
        mean_wasserstein
    )


