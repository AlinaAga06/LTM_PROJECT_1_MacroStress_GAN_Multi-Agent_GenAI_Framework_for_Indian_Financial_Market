# =============================================================================

def calculate_correlation_error(
    real_data,
    synthetic_data
):

    print()
    print("=" * 78)
    print("2. PAIRWISE CORRELATION")
    print("=" * 78)

    real_corr = np.corrcoef(
        real_data,
        rowvar=False
    )

    synthetic_corr = np.corrcoef(
        synthetic_data,
        rowvar=False
    )

    rows = []

    errors = []

    for i in range(
        len(FEATURE_NAMES)
    ):

        for j in range(
            i + 1,
            len(FEATURE_NAMES)
        ):

            real_value = real_corr[
                i,
                j
            ]

            synthetic_value = synthetic_corr[
                i,
                j
            ]

            error = abs(
                real_value
                - synthetic_value
            )

            errors.append(
                error
            )

            rows.append({

                "Feature_1":
                    FEATURE_NAMES[i],

                "Feature_2":
                    FEATURE_NAMES[j],

                "Real_Correlation":
                    real_value,

                "Synthetic_Correlation":
                    synthetic_value,

                "Absolute_Error":
                    error
            })

            print(
                f"{FEATURE_NAMES[i]:<24} vs "
                f"{FEATURE_NAMES[j]:<28} "
                f"Real={real_value: .4f} "
                f"Synthetic={synthetic_value: .4f} "
                f"Error={error:.4f}"
            )

    mean_error = np.mean(
        errors
    )

    print()
    print(
        f"Mean pairwise correlation error: "
        f"{mean_error:.6f}"
    )

    return (
        pd.DataFrame(rows),
        mean_error
    )


# =============================================================================
# LAG-1 CORRELATION
# =============================================================================

def calculate_lag1(
    sequences
):

    lag_values = []

    for feature_index in range(
        sequences.shape[2]
    ):

        correlations = []

        for sequence in sequences:

            current = sequence[
                :-1,
                feature_index
            ]

            next_values = sequence[
                1:,
                feature_index
            ]

            if (
                np.std(current) == 0
                or np.std(next_values) == 0
            ):

                continue

            correlation = np.corrcoef(
                current,
                next_values
            )[0, 1]

            if np.isfinite(
                correlation
            ):

                correlations.append(
                    correlation
                )

        if correlations:

            lag_values.append(
                np.mean(
                    correlations
                )
            )

        else:

            lag_values.append(
                np.nan
            )

    return np.array(
        lag_values
    )


